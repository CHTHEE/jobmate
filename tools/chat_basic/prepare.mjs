// Derive a SEPARATE basic protocol from the reviewed local scanner candidate.
// Never edits/executes the scanner SQL, original Chat SQL or a database.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
const root = new URL('../../',import.meta.url);
const read = path => readFileSync(new URL(path,root),'utf8').replaceAll('\r\n','\n');
const write = (path,text) => { mkdirSync(new URL('./',new URL(path,root)),{recursive:true});writeFileSync(new URL(path,root),text); };
function basic(text) {
  return text.replaceAll('chat_phase6b_backend_completion.md','chat_basic_attachments.md')
    .replaceAll('chat_phase6b_','chat_basic_')
    .replaceAll('chat_messages_attachment_binding_key','chat_messages_basic_attachment_binding_key')
    .replace(/\bchat_attachments\b/g,'chat_basic_attachments')
    .replaceAll('chat_attachments_owner_pending_idx','chat_basic_attachments_owner_pending_idx')
    .replaceAll('attachment_release','basic_attachment_release')
    .replaceAll('attachment_writes_enabled','basic_attachment_writes_enabled')
    .replaceAll('attachment_json','basic_attachment_json')
    .replaceAll('chat_files_','chat_basic_files_')
    .replaceAll('jobmate-chat-files','jobmate-chat-basic-files')
    .replaceAll('_v2','_basic_v1').replaceAll('v2','basic-v1')
    .replaceAll('10485760','5242880').replaceAll('scan','validation')
    .replaceAll('validationning','validating').replaceAll('validationned_at','validated_at')
    .replaceAll('approved','validated')
    .replaceAll("'application/msword',",'').replaceAll("'application/vnd.ms-excel',",'');
}
const sqlFiles = {
 'attachment_foundation':'attachment_migration',
 'rollback_validation_candidate':'rollback_validation_candidate',
 'security_tests':'security_tests',
 'empty_rollback_candidate':'empty_rollback_candidate',
 'catalog_verification':'catalog_verification',
};
for(const [oldName,newName] of Object.entries(sqlFiles)) {
  let sql = basic(read(`supabase/candidates/chat_phase6b_${oldName}.sql`));
  sql=sql.replace(/-- GENERATED[^\n]*\n/,'-- GENERATED by tools/chat_basic/prepare.mjs; separate basic protocol.\n');
  sql=sql.replaceAll('real validationner','trusted content validator');
  sql=sql.replace('isolated database/security validation and separate CH/KZ deployment approval required',
    'NO ANTIVIRUS: isolated basic validation/security tests and separate CH/KZ demo deployment approval required');
  sql=sql.replace('  validationner_version text,',"  validationner_version text,\n  validation_scope text NOT NULL DEFAULT 'basic-type-validation-no-antivirus-v1' CHECK (validation_scope='basic-type-validation-no-antivirus-v1'),");
  sql=sql.replace("'caption',a.caption,'original_name'","'validation_scope',a.validation_scope,'caption',a.caption,'original_name'");
  sql=sql.replaceAll('validationner_version','validator_version').replaceAll('p_validationner_version','p_validator_version');
  sql=sql.replace("OR p_verdict IS NULL OR p_sha256 IS NULL", "OR p_verdict IS NULL OR p_sha256 IS NULL");
  sql=sql.replace("OR (p_verdict='validated' AND p_sha256 IS DISTINCT FROM a.expected_sha256)",
    "OR (p_verdict='validated' AND (p_sha256 IS DISTINCT FROM a.expected_sha256 OR p_validator_version IS DISTINCT FROM 'basic-type-validation-no-antivirus-v1'))");
  sql=sql.replaceAll('Scan attempt','Validation attempt').replaceAll('Scan in progress','Validation in progress');
  sql=sql.replaceAll("'ISOLATED_SQL_MOCK_NOT_AV'", "'basic-type-validation-no-antivirus-v1'");
  sql=sql.replaceAll('Trusted service only','Trusted content-validator service only; NOT malware scanning');
  // The future scanner requirement is not weakened: separate tables, bucket,
  // functions and states below cannot transition a scanner reservation.
  write(`supabase/candidates/chat_basic_${newName}.sql`,
    '-- BASIC UNIVERSITY DEMO ONLY. Content/type validation is NOT antivirus.\n'+sql);
}
let protocol=basic(read('supabase/functions/_shared/chat_attachments/protocol.mjs'));
protocol=protocol.replaceAll('deps.validation(', 'deps.validate(')
  .replaceAll('validationner','validator')
  .replaceAll("op !== 'validation'", "op !== 'validate'")
  .replaceAll('validationner adapters','content validation adapters')
  .replaceAll('production mock switch','antivirus or mock scanner in this workflow');
write('supabase/functions/_shared/chat_basic/protocol.mjs',
  '// Separate BASIC content-validation protocol. No malware-scan claim.\n'+protocol);
let validator=read('tools/chat_scanner/validate.mjs');
validator="import { Buffer } from 'node:buffer';\n"+validator;
validator=validator.replace('10485760','5242880');
validator=validator.replace('function zipEntries(b) {',"function zipEntries(b) {\n  if (b.length < 22 || b.readUInt32LE(0) !== 0x04034b50) fail();");
validator=validator.replace('flags & 1 ||', '(flags & ~0x0808) ||');
validator=validator.replace('vba|macro|activex|embeddings|externallinks|\\.(zip|exe|dll|bin)$',
  'vba|macro|activex|embeddings|externallinks|\\.(zip|exe|dll|bin|com|scr|msi|js|vbs|ps1|cmd|bat|jar|hta|html|htm|svg|xhtml)$');
validator=validator.replace("if (/\\.(xml|rels)$/i.test(name) &&", "if (/\\.(xml|rels)$/i.test(name) && (bytes.includes(0) ||");
validator=validator.replace(".test(bytes.toString('utf8'))) fail();", ".test(bytes.toString('utf8')))) fail();");
validator=validator.replace('TargetMode\\s*=\\s*["\']External', 'TargetMode\\s*=\\s*["\'](?!Internal["\'])');
validator=validator.replace('let i = 2, found = false;', 'let i = 2, found = false, foundScan = false;');
validator=validator.replace("if (marker === 0xda) break;", `if (marker === 0xda) {
        const scanLength = b.readUInt16BE(i);
        if (scanLength < 6 || i + scanLength >= b.length - 2) fail();
        foundScan = true; break;
      }`);
validator=validator.replace("if (!found) fail(); mime = 'image/jpeg';", "if (!found || !foundScan) fail(); mime = 'image/jpeg';");
const oleStart=validator.indexOf('function oleType('), oleEnd=validator.indexOf('export function validateFile');
validator=validator.slice(0,oleStart)+validator.slice(oleEnd);
validator=validator.replace(/  } else if \(\['doc','xls'\]\.includes\(ext\)\) \{[\s\S]*?  } else fail\(\);/,'  } else fail();');
write('supabase/functions/_shared/chat_basic/validate.mjs',
  '// Bounded structural/type validation ONLY. No antivirus, no external service.\n'+validator);
let edge=read('supabase/functions/chat-attachments/index.ts');
edge=edge.replace('../_shared/chat_attachments/protocol.mjs','../_shared/chat_basic/protocol.mjs');
edge=edge.replace("const scanner = env('CHAT_SCANNER_URL');\nconst scannerKey = env('CHAT_SCANNER_SECRET');\n",'');
edge=edge.replace("env('CHAT_ATTACHMENTS_ENABLED')", "env('CHAT_BASIC_ATTACHMENTS_ENABLED')")
 .replace("env('CHAT_ATTACHMENT_CLEANUP_SECRET')", "env('CHAT_BASIC_CLEANUP_SECRET')")
 .replace("env('CHAT_ATTACHMENT_ALLOWED_ORIGIN')", "env('CHAT_BASIC_ALLOWED_ORIGIN')")
 .replace("scannerKey.length >= 32 && scanner.startsWith('https://') && cleanupKey.length >= 32",'cleanupKey.length >= 32');
const scanStart=edge.indexOf('  async scan('), scanEnd=edge.indexOf('\n  },',scanStart)+5;
edge=edge.slice(0,scanStart)+`  async validate(bytes: Uint8Array, row: { original_name: string; mime_type: string }) {
    const receipt = { sha256: await sha256(bytes), size_bytes: bytes.length,
      mime_type: row.mime_type, engine: 'basic-type-validation-no-antivirus-v1' };
    try { validateFile(bytes, row.original_name, row.mime_type); return { ...receipt, verdict: 'validated' }; }
    catch (_) { return { ...receipt, verdict: 'rejected' }; }
  },`+edge.slice(scanEnd);
edge=edge.replaceAll('_v2','_basic_v1');
write('supabase/functions/chat-basic-attachments/index.ts',
  "// Basic content validation only; never marks a file malware-free.\nimport { validateFile } from '../_shared/chat_basic/validate.mjs';\n"+edge);
console.log('Prepared separate guarded basic SQL, Edge protocol and local content validator. No scanner source or database changed.');
