import 'work_completion_report_data.dart';

/// Display precision only. The report data retains exact instants and durations.
class WorkReportFormat {
  const WorkReportFormat(this.data);
  final WorkCompletionReportData data;

  static const title = 'Attendance & Work Completion Report';
  static const introduction =
      'This report reflects recorded attendance, work completion and employer verification for the selected work assignment.';
  static const notice =
      'This report is system-generated from records available in JobMate at the time of generation and is provided as supporting documentation of the work assignment. Recorded attendance duration does not establish approved payable working hours or confirm payment.';
  static const footer =
      'Generated by JobMate — AI-Assisted Recruitment Platform';

  static const _months = [
    'Jan',
    'Feb',
    'Mar',
    'Apr',
    'May',
    'Jun',
    'Jul',
    'Aug',
    'Sep',
    'Oct',
    'Nov',
    'Dec',
  ];
  static DateTime _myt(DateTime value) =>
      value.toUtc().add(const Duration(hours: 8));
  static DateTime _displayInstant(DateTime value) => value.subtract(
    Duration(milliseconds: value.millisecond, microseconds: value.microsecond),
  );
  static String _two(int value) => value.toString().padLeft(2, '0');
  static String _date(DateTime myt) =>
      '${myt.day} ${_months[myt.month - 1]} ${myt.year}';

  static String time(DateTime value, {bool scheduled = false}) {
    final myt = _myt(value);
    final hour = myt.hour % 12;
    final seconds =
        !scheduled ||
            myt.second != 0 ||
            myt.millisecond != 0 ||
            myt.microsecond != 0
        ? ':${_two(myt.second)}'
        : '';
    return '${_date(myt)}, ${hour == 0 ? 12 : hour}:${_two(myt.minute)}'
        '$seconds ${myt.hour < 12 ? 'AM' : 'PM'} MYT';
  }

  String get start => time(data.scheduledStart, scheduled: true);
  String get end => time(data.scheduledEnd, scheduled: true);
  String get checkIn => time(data.checkInAt);
  String get checkOut => time(data.checkOutAt);
  String get verified => time(data.verifiedAt);
  String get generated => time(data.generatedAt);
  String get workDates {
    final start = _date(_myt(data.scheduledStart));
    final end = _date(_myt(data.scheduledEnd));
    return start == end ? start : '$start – $end';
  }

  String get filename {
    final date = _myt(data.scheduledStart);
    return 'JobMate_Work_Report_${date.year}-${_two(date.month)}-${_two(date.day)}.pdf';
  }

  String get scheduledDuration =>
      _elapsed(data.scheduledStart, data.scheduledEnd);
  String get recordedDuration => _elapsed(data.checkInAt, data.checkOutAt);
  String get checkInTiming => _offset(
    data.checkInAt,
    data.scheduledStart,
    'early',
    'after scheduled start',
  );
  String get checkOutTiming => _offset(
    data.checkOutAt,
    data.scheduledEnd,
    'before scheduled end',
    'after scheduled end',
  );
  String get submittedFiles =>
      '${data.submittedFileCount} ${data.submittedFileCount == 1 ? 'file' : 'files'} submitted';
  String get submission =>
      '${data.evidenceSubmissionStatus} · round ${data.verifiedRound}';
  String get completed => 'Completed';
  String get verification => 'Verified';
  String get verifier => data.verifiedBy;

  static String _elapsed(DateTime first, DateTime last) {
    final shown = _displayInstant(last).difference(_displayInstant(first));
    return shown == Duration.zero && last.isAfter(first)
        ? 'Less than 1 s'
        : _duration(shown);
  }

  static String _offset(
    DateTime actual,
    DateTime scheduled,
    String before,
    String after,
  ) {
    if (actual.isAtSameMomentAs(scheduled)) return 'On scheduled time';
    final displayed = _displayInstant(actual)
        .difference(_displayInstant(scheduled))
        .abs();
    final direction = actual.isBefore(scheduled) ? before : after;
    return displayed == Duration.zero
        ? 'Less than 1 s $direction'
        : '${_duration(displayed)} $direction';
  }

  static String _duration(Duration value) => [
    if (value.inHours != 0) '${value.inHours} h',
    if (value.inMinutes.remainder(60) != 0)
      '${value.inMinutes.remainder(60)} min',
    if (value.inSeconds.remainder(60) != 0 || value == Duration.zero)
      '${value.inSeconds.remainder(60)} s',
  ].join(' ');

  static List<String> location(ReportAttendanceLocation value) => [
    switch (value.status) {
      ReportLocationStatus.granted =>
        'Location permission granted. Address not recorded.',
      ReportLocationStatus.denied => 'Location permission denied.',
      ReportLocationStatus.unavailable => 'Location unavailable.',
      ReportLocationStatus.notRecorded => 'Location information not recorded.',
      null => 'Location information not available.',
    },
    if (value.originalEventAt case final event?)
      'Original attendance event: ${time(event)}',
  ];
}
